// Keep local render assets available to npm installs and standalone binaries.
import { readFileSync, readdirSync, mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
const require = createRequire(import.meta.url);
const katex = path.dirname(require.resolve("katex/dist/katex.min.css"));
const files = {
  "KaTeX-LICENSE.txt": readFileSync(path.join(katex, "..", "LICENSE")).toString(
    "base64",
  ),
  "gsap.min.js": readFileSync(
    require.resolve("gsap/dist/gsap.min.js"),
  ).toString("base64"),
  "katex.min.js": readFileSync(path.join(katex, "katex.min.js")).toString(
    "base64",
  ),
  "katex.min.css": readFileSync(path.join(katex, "katex.min.css")).toString(
    "base64",
  ),
};
for (const name of readdirSync(path.join(katex, "fonts"))) {
  files[`fonts/${name}`] = readFileSync(
    path.join(katex, "fonts", name),
  ).toString("base64");
}
const out = new URL("../src/video/assets.ts", import.meta.url);
mkdirSync(new URL("../src/video/", import.meta.url), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/build-video-assets.mjs.\nexport const VIDEO_ASSETS: Record<string, string> = ${JSON.stringify(files)};\n`,
);
const examples = Object.fromEntries(
  readdirSync(new URL("../examples/video/", import.meta.url))
    .filter((n) => n.endsWith(".json"))
    .map((n) => [
      n.slice(0, -5),
      JSON.parse(
        readFileSync(
          new URL(`../examples/video/${n}`, import.meta.url),
          "utf8",
        ),
      ),
    ]),
);
writeFileSync(
  new URL("../src/video/examples.ts", import.meta.url),
  `// Generated by scripts/build-video-assets.mjs.\nexport const VIDEO_EXAMPLES: Record<string, unknown> = ${JSON.stringify(examples)};\n`,
);
